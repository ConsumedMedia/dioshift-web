import type { Metadata } from "next";
import { formatPrice, getPackageRange } from "@/lib/packages";
import { siteConfig } from "@/lib/site-config";

/** Appended to every page title by the root layout's title template. */
export const TITLE_SUFFIX = ` | ${siteConfig.name}`;

/** Homepage title, also the fallback for any page that doesn't set one. */
export const DEFAULT_TITLE = `Streaming TV Ads for Local Businesses${TITLE_SUFFIX}`;

/** Lowest monthly plan price, e.g. "$1,875". Always read from lib/packages.ts. */
export const STARTING_PRICE = formatPrice(getPackageRange().min.monthlyPrice);

/** Homepage description, also the fallback for any page that doesn't set one. */
export const DEFAULT_DESCRIPTION = `Get your business on streaming TV from ${STARTING_PRICE} a month. Guaranteed impressions, no contract, and we handle the setup. Based in Columbus, Ohio.`;

/**
 * The share image generated by app/opengraph-image.tsx. Listed explicitly
 * because a page that sets its own openGraph/twitter object doesn't inherit
 * the root segment's file-based image.
 */
const SHARE_IMAGE = {
  url: "/opengraph-image",
  width: 1200,
  height: 630,
  alt: `${siteConfig.name}: your business on streaming TV`,
  type: "image/png",
};

/**
 * Per-page metadata. Next.js replaces (not merges) openGraph/twitter objects
 * from the root layout, so the shared fields are repeated here.
 *
 * `path` sets the canonical URL (resolved against metadataBase in the root
 * layout). Leave it out only on pages that are noindex.
 */
export function pageMetadata({
  title,
  description,
  path,
  absoluteTitle = false,
}: {
  title: string;
  description: string;
  path?: string;
  /** Use `title` as is, without the " | Dioshift" suffix (homepage). */
  absoluteTitle?: boolean;
}): Metadata {
  const fullTitle = absoluteTitle ? title : `${title}${TITLE_SUFFIX}`;
  return {
    title: absoluteTitle ? { absolute: title } : title,
    description,
    ...(path && { alternates: { canonical: path } }),
    openGraph: {
      type: "website",
      siteName: siteConfig.name,
      locale: "en_US",
      title: fullTitle,
      description,
      ...(path && { url: path }),
      images: [SHARE_IMAGE],
    },
    twitter: { card: "summary_large_image", title: fullTitle, description, images: [SHARE_IMAGE] },
  };
}
